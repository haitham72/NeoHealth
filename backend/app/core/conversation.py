"""Small-talk router: the conversational layer in front of the retrieval pipeline.

Without it, "hi" runs the whole machine -- an embedding call, a hybrid search, RRF,
confidence tiering, then an LLM relevance verdict -- only to come back with
guardrail.py's off-topic template ("This looks like it's about project details, which
is out of scope for UAE health regulation..."). That is the wrong register for a
greeting and it isn't free. This module answers those inputs at the very top of both
entry points: zero embeddings, zero LLM calls, zero DB reads, and nothing enters the
answer cache.

**Deterministic only -- no model call decides anything here.** Two guards make a false
positive on a real regulation question essentially impossible:

1. *Whole-string anchored match.* The input is normalized (lowercased, punctuation and
   diacritics stripped, whitespace collapsed) and then the ENTIRE normalized string
   must equal a known phrase. "hi" routes; "hi, what are the DHA licensing fees?" does
   not, and falls through to the real pipeline untouched.
2. *Word ceiling.* Anything over MAX_SMALLTALK_WORDS words is never even considered.

Every response is a fixed string, never model prose -- the same discipline
guardrail.py already uses for build_offtopic_message()/validate_redirect(). The one
response that varies, `model`, is composed at call time from the actual configured
model constants so it can never drift from what the app really runs.
"""
