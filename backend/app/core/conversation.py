def normalize(text: str) -> str:
    """Lowercase, strip diacritics, drop punctuation, collapse whitespace. NFKD plus
    combining-mark removal handles both Latin accents and Arabic harakat, so
    "أهلاً" and "اهلا" normalize to the
    same string."""
    decomposed = unicodedata.normalize("NFKD", text or "")
    stripped = "".join(ch for ch in decomposed if not unicodedata.combining(ch))
    lowered = stripped.lower()
    # \w keeps letters (any script) and digits; everything else becomes a space, so
    # trailing "!", "?" and "..." can't stop a phrase from matching.
    words = re.sub(r"[^\w\s]|_", " ", lowered)
    return re.sub(r"\s+", " ", words).strip()


# Built once at import: normalized phrase -> intent. A phrase appearing under two
# intents would silently shadow, so the build asserts uniqueness rather than letting
# dict order decide.
_INTENT_BY_PHRASE: dict[str, str] = {}
for _intent, _spec in INTENTS.items():
    for _phrase in _spec["phrases"]:
        _key = normalize(_phrase)
        if _key in _INTENT_BY_PHRASE:
            raise ValueError(
                f"small-talk phrase {_key!r} is claimed by both "
                f"{_INTENT_BY_PHRASE[_key]!r} and {_intent!r}"
            )
        _INTENT_BY_PHRASE[_key] = _intent


def response_for(intent: str) -> str:
    """The fixed text for an intent; `model`'s is composed from config at call time."""
    response = INTENTS[intent]["response"]
    return response() if callable(response) else response


def match_intent(question: str) -> str | None:
    """The whole matcher: normalize, refuse anything over the word ceiling, then look
    up the entire normalized string. Exposed separately from route() so tests (and any
    future caller) can assert routing decisions without building a result dict."""
    normalized = normalize(question)
    if not normalized:
        return None
    if len(normalized.split()) > MAX_SMALLTALK_WORDS:
        return None
    return _INTENT_BY_PHRASE.get(normalized)


def route(question: str) -> dict | None:
    """Returns a ready-to-serve abstention dict for small talk, or None to let the
    real pipeline handle the input.

    The shape mirrors the existing off-topic abstention (see retrieval.py's guardrail
    branch) so app/api/routers/ can keep passing the dict straight through as JSON:
    `smalltalk` and `intent` are additive flags, and `suggested_followups` uses the
    same {"question": ...} element shape the mined suggestions use, so the frontend
    renders them through the same FollowUpQuestions component. `run_id` is attached by
    the caller, which owns the trace."""
    intent = match_intent(question)
    if intent is None:
        return None
    return {
        "abstained": True,
        "smalltalk": True,
        "intent": intent,
        "reason": response_for(intent),
        "suggested_followups": [{"question": q} for q in INTENTS[intent]["starters"]],
    }
